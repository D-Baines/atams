void swapEndiannessRaw(uint8_t* buffer, uint8_t bufferLength)
{ 
  for (uint8_t i = 0U; i < bufferLength / 2U; ++i)
  {
    uint8_t temp                  = buffer[i];
    buffer[i]                     = buffer[bufferLength - i - 1U];
    buffer[bufferLength - i - 1U] = temp;
  }
}


